import { defineConfig, loadEnv } from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, ".", "BACKEND_API_URL");
  return {
    plugins: [react()],
    server: {
      host: "127.0.0.1",
      port: 5173,
      strictPort: true,
      proxy: {
        "/api": {
          target: env.BACKEND_API_URL || "http://127.0.0.1:8000",
          changeOrigin: true,
        },
      },
    },
  };
});
